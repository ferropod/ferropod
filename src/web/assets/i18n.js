  function detectLocale() {
    var saved = null;
    try {
      saved = localStorage.getItem(STORAGE_KEY);
    } catch (_) {}
    if (saved && DICT[saved]) return saved;
    var nav = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
    return nav.indexOf('zh') === 0 ? 'zh-CN' : 'en';
  }

  var currentLocale = detectLocale();

  function getLocale() {
    return currentLocale;
  }

  function setLocale(lang) {
    if (!DICT[lang]) return currentLocale;
    currentLocale = lang;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (_) {}
    if (document && document.documentElement) {
      document.documentElement.lang = lang;
    }
    return currentLocale;
  }

  function t(key, vars) {
    var pack = DICT[currentLocale] || DICT.en;
    var text = Object.prototype.hasOwnProperty.call(pack, key)
      ? pack[key]
      : (Object.prototype.hasOwnProperty.call(DICT.en, key) ? DICT.en[key] : key);
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        text = text.replace(new RegExp('\\{' + k + '\\}', 'g'), String(vars[k]));
      });
    }
    return text;
  }

  function formatTime(ts) {
    if (ts === null || ts === undefined || ts === '') return '-';
    var num = Number(ts);
    if (!Number.isFinite(num) || num <= 0) return '-';
    var ms = num < 1e12 ? num * 1000 : num;
    try {
      return new Intl.DateTimeFormat(currentLocale, {
        year: 'numeric',
        month: '2-digit',
        day: '2-digit',
        hour: '2-digit',
        minute: '2-digit',
        second: '2-digit',
        hour12: false
      }).format(new Date(ms));
    } catch (_) {
      return new Date(ms).toISOString();
    }
  }

  function formatBytes(bytes) {
    var n = Number(bytes || 0);
    if (!Number.isFinite(n) || n <= 0) return '0 B';
    var units = ['B', 'KiB', 'MiB', 'GiB', 'TiB'];
    var idx = Math.min(Math.floor(Math.log(n) / Math.log(1024)), units.length - 1);
    var val = n / Math.pow(1024, idx);
    return (idx === 0 ? String(n) : val.toFixed(val >= 10 ? 1 : 2)) + ' ' + units[idx];
  }

  setLocale(currentLocale);

  window.FerroI18n = {
    DICT: DICT,
    detectLocale: detectLocale,
    getLocale: getLocale,
    setLocale: setLocale,
    t: t,
    formatTime: formatTime,
    formatBytes: formatBytes
  };
